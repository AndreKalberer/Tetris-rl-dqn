"""Watch a saved original-game run in Mesen, with a live info panel.

Writes a small Lua script (the recorded controller bytes and score timeline go in
side files it reads, since Mesen opens the script in its editor) and opens a
separate viewer copy of Mesen with the same emulation profile the bot used.
The script feeds one byte each time the game polls the controller, exactly as
nes_original/mesen_bridge.lua did during play. It never writes game memory.
Playback starts one second before the game itself: the bot's level-select wait
(menu_wait_seed frames, minutes for big seeds) is replayed once in Mesen's
background mode to make a cached sync savestate.

  python nes-bot/tools/watch_replay.py runs/nes-255-crash-map-v3/seed81/cases/seed-81.json

The panel (over the piece-statistics box) shows:
  SCORE  uncapped ("theoretical") score, from nes_original.theoretical_score;
         the cartridge itself stops at 999,999. Needs the run's events file.
  LEVEL  the game's level counter as a number (its own display garbles past 29)
  LINES  the game's line counter
Speed: --speed sets Mesen's own speed at launch. Live, with the game window
focused: Options > Speed (Normal, Increase, Decrease, Maximum, Triple, Double...),
the keys = (faster: 150, 200, ... 500, 750, 1000%) and - (slower), F9 (maximum
on/off), or hold Tab (--tab-speed, default maximum). The panel shows the speed
actually reached: with a script loaded Mesen runs its debugger, which caps this
machine at about 235 frames/s (3.9x), so 500% and up all play at about 3.9x.
(A script-side speed control froze the window, so there is none.) Speed never
changes the game: inputs follow the game's own controller polls.

The viewer copy lives next to the pinned bot emulator (mesence-2.2.1-viewer) so
the bot's own portable profile (settings.json = {}) is never touched.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]  # nes-bot/
REPO = ROOT.parent  # repository root: runs/ and progress.md live here
sys.path.insert(0, str(ROOT))
from nes_original.mesen import PROFILE  # noqa: E402

DEFAULT_MESEN = REPO.parent/'nes-late-fidelity'/'mesence-2.2.1'/'Mesen.exe'

LUA = r'''-- Generated by tools/watch_replay.py: replays recorded controller bytes.
-- The recording and score timeline live in data files next to this script: a
-- huge literal here freezes Mesen's script editor, which opens with the script.
local inputFile = assert(io.open(INPUT_FILE, "rb"))
local inputs = inputFile:read("a")
inputFile:close()
local total = #inputs
local index = 0
local seedLabel = SEED_LABEL
-- Uncapped score after each piece: {controller-read index, score, ...}
local scores = {}
local scoreFile = io.open(SCORE_FILE, "r")
if scoreFile then
  for line in scoreFile:lines() do
    local i, v = line:match("^(%d+),(%d+)$")
    if i then scores[#scores + 1] = tonumber(i); scores[#scores + 1] = tonumber(v) end
  end
  scoreFile:close()
end
local scorePos = 0
local currentScore = nil

-- A normal Mesen window attaches this script at an unpredictable moment after
-- power-on. To start in exact sync, load a savestate made by the bot's own
-- background mode (script attached before power-on) after SYNC_INDEX reads.
local synced = false
local syncFile = io.open(SYNC_STATE, "rb")
local syncState = syncFile and syncFile:read("a")
if syncFile then syncFile:close() end
local syncError = nil
if not syncState then syncError = "sync savestate not readable" end

-- Savestates can only be loaded inside a CPU exec callback, so arm one at the
-- next frame start and remove it once the state is loaded.
local armed = false
local loader = nil
emu.addEventCallback(function()
  if synced or armed or not syncState then return end
  armed = true
  loader = emu.addMemoryCallback(function()
    if synced or not loader then return end
    local ok, err = pcall(emu.loadSavestate, syncState)
    if ok then
      synced = true
      index = SYNC_INDEX
    else
      syncError = tostring(err)
    end
    local ref = loader
    loader = nil
    pcall(emu.removeMemoryCallback, ref, emu.callbackType.exec, 0x8000, 0xFFFF)
  end, emu.callbackType.exec, 0x8000, 0xFFFF)
end, emu.eventType.startFrame)

emu.addEventCallback(function()
  if not synced then
    emu.setInput({}, 0, 0)  -- neutral until the savestate is loaded
    return
  end
  index = index + 1
  local value = 0
  if index <= total then value = inputs:byte(index) end
  emu.setInput({a=value%2>=1,b=(value//2)%2>=1,select=(value//4)%2>=1,start=(value//8)%2>=1,
    up=(value//16)%2>=1,down=(value//32)%2>=1,left=(value//64)%2>=1,right=(value//128)%2>=1}, 0, 0)
  while scorePos + 2 <= #scores and scores[scorePos + 1] <= index do
    currentScore = scores[scorePos + 2]
    scorePos = scorePos + 2
  end
end, emu.eventType.inputPolled)

local function ram(address) return emu.read(address, emu.memType.nesInternalRam) end
local function bcd(byte) return (byte >> 4) * 10 + (byte & 15) end
local function commas(n)
  local s = tostring(math.floor(n))
  while true do
    local t, k = s:gsub("^(%d+)(%d%d%d)", "%1,%2")
    s = t
    if k == 0 then return s end
  end
end

local debugLog = DEBUG_LOG ~= "" and io.open(DEBUG_LOG, "w") or nil
local lastError = nil
local frames = 0
-- Actual playback speed, measured every 60 frames (Mesen's own limit can't be
-- reached when the machine is slower; the debugger a script needs costs a lot).
local speedText = "-"
local speedClock = os.clock()

local function panel()
  local level = ram(0x44)
  local lines = bcd(ram(0x50)) + 100 * ram(0x51)
  local capped = bcd(ram(0x53)) + 100 * bcd(ram(0x54)) + 10000 * bcd(ram(0x55))
  -- The timeline knows a piece's points only at the next lock, so while the
  -- cartridge score is below its 999,999 cap it is the same number, sooner.
  local score = math.max(currentScore or 0, capped)
  -- Black panel over the piece-statistics box (Mesen colours: alpha 00 = opaque, FF = transparent).
  emu.drawRectangle(2, 60, 90, 168, 0x000000, true)
  emu.drawRectangle(2, 60, 90, 168, 0x808080, false)
  emu.drawString(6, 64, seedLabel, 0xFFFFFF, 0xFF000000)
  emu.drawString(6, 80, "SCORE", 0xA0A0A0, 0xFF000000)
  emu.drawString(6, 90, commas(score), 0xFFFF40, 0xFF000000)
  if capped >= 999999 then emu.drawString(6, 100, "(cartridge: 999,999)", 0x808080, 0xFF000000) end
  emu.drawString(6, 116, "LEVEL", 0xA0A0A0, 0xFF000000)
  emu.drawString(6, 126, tostring(level), 0x40FF40, 0xFF000000)
  emu.drawString(6, 142, "LINES", 0xA0A0A0, 0xFF000000)
  emu.drawString(6, 152, commas(lines), 0x40C0FF, 0xFF000000)
  if index >= total then emu.drawString(6, 168, "end of recording", 0xFF8080, 0xFF000000) end
  emu.drawString(6, 176, "SPEED " .. speedText, 0xA0A0A0, 0xFF000000)
  emu.drawString(6, 190, "Options>Speed", 0xFFFFFF, 0xFF000000)
  emu.drawString(6, 200, "keys: = faster", 0xFFFFFF, 0xFF000000)
  emu.drawString(6, 210, "- slower", 0xFFFFFF, 0xFF000000)
  emu.drawString(6, 220, "hold Tab: max", 0xFFFFFF, 0xFF000000)
  if not synced then emu.drawString(4, 2, "NOT SYNCED: " .. tostring(syncError), 0xFF4040, 0x000000) end
end

emu.addEventCallback(function()
  local ok, err = pcall(panel)
  if not ok then
    lastError = tostring(err)
    emu.drawString(2, 2, "panel error: " .. lastError, 0xFF4040, 0x000000)
  end
  frames = frames + 1
  if frames % 60 == 0 then
    local now = os.clock()
    if now > speedClock then speedText = string.format("%.1fx", 60 / 60.0988 / (now - speedClock)) end
    speedClock = now
  end
  if debugLog and frames % 300 == 0 then
    debugLog:write(string.format("t=%.2f frame=%d index=%d/%d level=%d lines=%02x%02x synced=%s score=%s ram_score=%02x%02x%02x error=%s\n",
      os.clock(), frames, index, total, ram(0x44), ram(0x51), ram(0x50), tostring(synced), tostring(currentScore),
      ram(0x55), ram(0x54), ram(0x53),
      tostring(lastError or syncError)))
    debugLog:flush()
  end
end, emu.eventType.endFrame)
'''


SYNC_LUA = r'''-- Generated by tools/watch_replay.py: exact sync savestate for the viewer.
-- Runs in Mesen's background test mode, attached before power-on like the bot's bridge.
local inputFile = assert(io.open(INPUT_FILE, "rb"))
local inputs = inputFile:read("a")
inputFile:close()
local index = 0
emu.addEventCallback(function()
  index = index + 1
  local value = inputs:byte(index) or 0
  emu.setInput({a=value%2>=1,b=(value//2)%2>=1,select=(value//4)%2>=1,start=(value//8)%2>=1,
    up=(value//16)%2>=1,down=(value//32)%2>=1,left=(value//64)%2>=1,right=(value//128)%2>=1}, 0, 0)
end, emu.eventType.inputPolled)
local armed = false
local function save()
    local ok, state = pcall(emu.createSavestate)
    local g = io.open(OUT_INDEX, "w")
    if ok and state then
      local f = io.open(OUT_STATE, "wb"); f:write(state); f:close()
      g:write(tostring(index))
    else
      g:write("error: " .. tostring(state))
    end
    g:close()
    emu.stop(0)
end
-- Savestates are only allowed inside a CPU exec callback; arm one at the target frame.
emu.addEventCallback(function()
  if index >= TARGET and not armed then
    armed = true
    local done = false
    emu.addMemoryCallback(function()
      if not done then done = true; save() end
    end, emu.callbackType.exec, 0x8000, 0xFFFF)
  end
end, emu.eventType.startFrame)
'''
SYNC_LEAD = 60  # start the viewer this many controller reads before the game starts


def sync_target(record):
    """Controller-read index to start the viewer at: shortly before the game starts.

    The bot sits on the level-select screen for menu_wait_seed frames to set the
    piece sequence (19,211 frames, over five minutes, for seed 19211). Starting
    there would show only the flashing level "8" for minutes, so the sync
    savestate skips the menu wait. The inputs before it are all fed for real.
    """
    return max(60, int(record.get('start_frame', 0)) - SYNC_LEAD)


def sync_state(exe, rom, input_file, target, folder):
    """Savestate after `target` recorded reads, made the way the bot's emulator ran.

    Background mode runs only ~250 frames/s here, so a long menu wait takes over a
    minute; the state is cached next to the record, keyed by everything it depends on.
    """
    state, index_file = folder/'viewer-sync.mss', folder/'viewer-sync.index'
    key_file, script = folder/'viewer-sync.key', folder/'viewer-sync.lua'
    inputs = input_file.read_bytes()
    key = hashlib.sha256(json.dumps([inputs[:target+64].hex(), target, list(PROFILE),
                                     hashlib.sha256(rom.read_bytes()).hexdigest(),
                                     hashlib.sha256(SYNC_LUA.encode()).hexdigest()]).encode()).hexdigest()
    if (key_file.is_file() and key_file.read_text() == key and state.is_file()
            and index_file.is_file() and index_file.read_text().isdigit()):
        return state, int(index_file.read_text())
    for path in (state, index_file, key_file):
        if path.exists():
            path.unlink()
    seconds = target//250 + 30
    print(f'Making the sync savestate ({target} controller reads; up to ~{seconds} s, cached afterwards)...',
          flush=True)
    script.write_text(SYNC_LUA.replace('INPUT_FILE', json.dumps(input_file.resolve().as_posix()))
        .replace('TARGET', str(target)).replace('OUT_STATE', json.dumps(state.resolve().as_posix()))
        .replace('OUT_INDEX', json.dumps(index_file.resolve().as_posix())), encoding='utf-8')
    subprocess.run([str(exe), '--testRunner', f'--timeout={seconds*3}', '--doNotSaveSettings',
                    '--debug.scriptwindow.allowioosaccess=true', *PROFILE, str(script.resolve()),
                    str(rom.resolve())], cwd=exe.parent, timeout=seconds*3+60, capture_output=True)
    if not index_file.is_file():
        raise RuntimeError('Mesen did not run the sync script')
    if not index_file.read_text().isdigit() or not state.is_file():
        raise RuntimeError('Mesen could not make the sync savestate: '+index_file.read_text())
    key_file.write_text(key)
    return state, int(index_file.read_text())


def viewer(executable):
    source = Path(executable).resolve().parent
    target = source.with_name(source.name+'-viewer')
    if not target.exists():
        shutil.copytree(source, target, ignore=shutil.ignore_patterns('SaveStates','Saves','*.log'))
    return target/'Mesen.exe'


def events_for(record_path, seed):
    """The run's gameplay events file, next to its cases/ folder."""
    candidate = record_path.resolve().parent.parent/f'gameplay-seed-{seed}-events.jsonl'
    return candidate if candidate.is_file() else None


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('record', type=Path, help='cases/seed-*.json saved replay record')
    p.add_argument('--mesen', type=Path, default=DEFAULT_MESEN, help='the bot\'s portable Mesen.exe (copied, not used)')
    p.add_argument('--rom', type=Path, help='original Tetris (USA) image; default: the bundled gym_tetris copy')
    p.add_argument('--events', type=Path, help='gameplay events file for the uncapped score (default: found next to the record)')
    p.add_argument('--no-launch', action='store_true', help='only write the Lua script')
    p.add_argument('--debug-log', type=Path, help=argparse.SUPPRESS)
    p.add_argument('--tab-speed', type=int, default=0,
                   help='speed in percent while Tab (fast-forward) is held; 0 = as fast as the machine can (default)')
    p.add_argument('--speed', type=int, default=100,
                   help="Mesen emulation speed in percent (100 normal, 300 triple, 0 maximum); change it live with "
                        "Options > Speed, the = and - keys, F9, or by holding Tab")
    args = p.parse_args()
    record = json.loads(args.record.read_text(encoding='utf-8'))
    if 'mesence' not in record.get('protocol',''):
        p.error('This tool replays MesenCE reference records only')
    if any(bytes.fromhex(record['input_hex'][:240])):
        p.error('Record does not start with neutral boot input; late script attach cannot be synced')
    rom = args.rom
    if rom is None:
        from nes_original.env import bundled_rom
        rom = Path(bundled_rom())
    seed = record['menu_wait_seed']
    events = args.events or events_for(args.record, seed)
    timeline = []
    if events:
        from nes_original.theoretical_score import timeline as score_timeline
        timeline = score_timeline(events)
    else:
        print('No events file found: the panel shows the cartridge score (stops at 999,999).')
    exe = viewer(args.mesen)
    script = args.record.with_name(args.record.stem+'-watch.lua')
    input_file = args.record.with_name(args.record.stem+'-watch.inputs')
    input_file.write_bytes(bytes.fromhex(record['input_hex']))
    state, sync_index = sync_state(exe, rom, input_file, sync_target(record), args.record.resolve().parent)
    score_file = args.record.with_name(args.record.stem+'-watch.scores')
    score_file.write_text(''.join(f'{i},{v}\n' for i, v in timeline), encoding='ascii')
    lua = (LUA.replace('INPUT_FILE', json.dumps(input_file.resolve().as_posix()))
              .replace('SCORE_FILE', json.dumps(score_file.resolve().as_posix()))
              .replace('SYNC_STATE', json.dumps(state.resolve().as_posix()))
              .replace('SYNC_INDEX', str(sync_index))
              .replace('SEED_LABEL', json.dumps(f'Bot - seed {seed}'))
              .replace('DEBUG_LOG', json.dumps(args.debug_log.resolve().as_posix() if args.debug_log else '')))
    script.write_text(lua, encoding='utf-8')
    print(f'Wrote {script} ({len(record["input_hex"])//2} controller bytes, {len(timeline)} score updates)')
    if args.no_launch:
        return
    command = [str(exe), '--doNotSaveSettings', '--debug.scriptwindow.allowioosaccess=true', *PROFILE,
               f'--emulation.emulationSpeed={args.speed}', f'--emulation.turboSpeed={args.tab_speed}', str(script.resolve()), str(rom.resolve())]
    # Detached, with no inherited handles, so the caller returns at once.
    subprocess.Popen(command, cwd=exe.parent, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                     stderr=subprocess.DEVNULL, close_fds=True,
                     creationflags=getattr(subprocess, 'DETACHED_PROCESS', 0) |
                     getattr(subprocess, 'CREATE_NEW_PROCESS_GROUP', 0))
    print('Opened Mesen. Speed (click the game window first): Options > Speed, keys = / - to step, F9 maximum,'
          ' hold Tab for maximum. This machine tops out near 3.9x while the panel script runs (shown in the panel).'
          ' Mesen also opens a Script Window: minimise it, but closing it stops the replay.')


if __name__=='__main__':
    main()
